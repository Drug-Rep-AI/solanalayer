/**
 * Converts a snarkjs verification_key.json into the `Groth16Verifyingkey`
 * constant used by groth16-solana (big endian, G2 as x.c1|x.c0|y.c1|y.c0).
 *
 * usage: tsx scripts/vk-to-rust.ts <verification_key.json> <out.rs>
 */
import { readFileSync, writeFileSync } from "node:fs";
import { encodeVk, type SnarkjsVk } from "@drugrep/sdk";

const [inPath, outPath] = process.argv.slice(2);
if (!inPath || !outPath) {
  console.error("usage: tsx scripts/vk-to-rust.ts <verification_key.json> <out.rs>");
  process.exit(1);
}
const vk = JSON.parse(readFileSync(inPath, "utf8")) as SnarkjsVk;
const e = encodeVk(vk);
const arr = (b: Uint8Array) => {
  const parts = Array.from(b, (x) => `${x}`);
  const lines: string[] = [];
  for (let i = 0; i < parts.length; i += 16) lines.push("        " + parts.slice(i, i + 16).join(", ") + ",");
  return `[\n${lines.join("\n")}\n    ]`;
};
const ic = e.ic.map((p) => "    " + arr(p).replace(/\n {4}\]/, "\n    ]")).join(",\n");
const rs = `// @generated by scripts/vk-to-rust.ts from circuits/build/verification_key.json.
// POC trusted setup, not for production. Do not edit by hand: rerun
// \`pnpm circuit:setup\` to regenerate the circuit keys and this file together.

use groth16_solana::groth16::Groth16Verifyingkey;

pub const NR_PUBLIC_INPUTS: usize = ${vk.nPublic};

pub const VERIFYING_KEY: Groth16Verifyingkey = Groth16Verifyingkey {
    nr_pubinputs: ${vk.nPublic},
    vk_alpha_g1: ${arr(e.alpha)},
    vk_beta_g2: ${arr(e.beta)},
    vk_gamme_g2: ${arr(e.gamma)},
    vk_delta_g2: ${arr(e.delta)},
    vk_ic: &[
${ic},
    ],
};
`;
writeFileSync(outPath, rs);
console.log(`wrote ${outPath} (${vk.nPublic} public inputs, ${e.ic.length} IC points)`);
